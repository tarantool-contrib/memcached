-- Check the memcached rock a project installed (test/rock/consumer.sh), run
-- in the project: every module named in the arguments loads from its .rocks,
-- the C data path is there and of the engine's ABI, the thread transport
-- (memcached.ipc) of the threads' ABI, the version is tt's, and an instance
-- answers a set and a get.
--
--   tarantool check.lua memcached memcached.engine ... roles.memcached

local fio = require('fio')
local socket = require('socket')

local function check()
    local rocks = fio.abspath('.rocks')
    local names = {}
    for i = 1, #arg do
        table.insert(names, arg[i])
    end
    assert(#names > 0, 'no modules to check')
    -- Generated by tt and built by tt: no source file of their own.
    table.insert(names, 'memcached.version')
    table.insert(names, 'memcached.datapath')
    table.insert(names, 'memcached.ipc')
    for _, name in ipairs(names) do
        local path = package.search(name) -- luacheck: ignore 143
        assert(
            path ~= nil and path:sub(1, #rocks + 1) == rocks .. '/',
            ('%s is not loaded from %s: %s'):format(
                name,
                rocks,
                tostring(path)
            )
        )
        require(name)
        print(('ok %s %s'):format(name, path:sub(#rocks + 2)))
    end

    local mcc = require('memcached')
    local engine = require('memcached.engine')
    local server = require('memcached.server')
    local datapath = require('memcached.datapath')
    assert(
        datapath.ABI == engine.DATAPATH_ABI,
        ('datapath ABI %s, the engine wants %s'):format(
            datapath.ABI,
            engine.DATAPATH_ABI
        )
    )
    local ipc = require('memcached.ipc')
    assert(
        ipc.ABI == require('memcached.threads').IPC_ABI,
        ('ipc ABI %s, the threads want %s'):format(
            ipc.ABI,
            require('memcached.threads').IPC_ABI
        )
    )
    local version = require('memcached.version').version
    assert(mcc.VERSION == version, mcc.VERSION)
    print(('ok version %s, datapath ABI %s'):format(version, datapath.ABI))

    local dir = fio.tempdir()
    box.cfg {
        memtx_dir = dir,
        wal_dir = dir,
        vinyl_dir = dir,
        log = fio.pathjoin(dir, 'tarantool.log'),
    }
    assert(mcc.datapath().available, 'the C data path is not available')
    local s = socket('AF_INET', 'SOCK_STREAM', 'tcp')
    assert(s:bind('127.0.0.1', 0))
    local port = s:name().port
    s:close()
    mcc.create('check', {listen = '127.0.0.1:' .. port})
    local c = assert(socket.tcp_connect('127.0.0.1', port))
    c:write('set k 0 0 5\r\nhello\r\nget k\r\nversion\r\n')
    local want = 'STORED\r\nVALUE k 0 5\r\nhello\r\nEND\r\nVERSION '
        .. server.version()
        .. '\r\n'
    local got = c:read(#want, 10)
    c:close()
    assert(got == want, ('set/get/version: %q, want %q'):format(got, want))
    print(('ok set, get, version: %s'):format(server.version()))
    mcc.destroy('check')
    fio.rmtree(dir)
end

local ok, err = pcall(check)
if not ok then
    io.stderr:write(tostring(err), '\n')
    os.exit(1)
end
os.exit(0)
